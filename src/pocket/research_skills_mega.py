"""ResearchersHub mega skill pack — expands catalog past 750 research skills.

Readable · editable · extensible. Loaded by science_skills alongside core + ext packs.
"""

from __future__ import annotations

from typing import Any, Dict, List


def _s(
    id: str,
    domain: str,
    desc: str,
    *,
    kind: str = "playbook",
    tags: str = "",
    worker: str = "SCRUTATOR",
) -> Dict[str, Any]:
    t = tags.split() if tags else []
    t = list(dict.fromkeys([domain.lower(), "science", "research"] + t))
    return {
        "id": id,
        "worker": worker,
        "desc": desc,
        "kind": kind,
        "tags": t,
        "domain": domain,
        "product": "ResearchersHub",
        "editable": True,
        "extensible": True,
    }


def _pack(domain: str, items: List[tuple], tags: str = "") -> List[Dict[str, Any]]:
    return [_s(i, domain, d, tags=tags) for i, d in items]


