def all_mega_skills() -> List[Dict[str, Any]]:
    packs = [
        _ml_deep(),
        _compbio_deep(),
        _cheminf_deep(),
        _clinical_stats(),
        _materials_physics(),
        _earth_climate(),
        _neuro_cog(),
        _astro_space(),
        _robotics_eng(),
        _data_platform(),
        _viz_writing(),
        _atlas_agents(),
        _quantum_theory(),
    ]
    seen = set()
    out: List[Dict[str, Any]] = []
    for pack in packs:
        for s in pack:
            if s["id"] in seen:
                continue
            seen.add(s["id"])
            out.append(s)
    return out


def mega_count() -> int:
    return len(all_mega_skills())
